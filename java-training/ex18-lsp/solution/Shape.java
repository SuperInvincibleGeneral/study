/**
 * 課題18 解答例: すべての図形が守る契約。
 *
 * リスコフの置換原則（LSP）:
 *   「サブタイプは、その基底型として使われている場所で、そのまま置き換えられなければならない」
 *
 * ここで決めた契約は次の2つ。どの実装でも必ず成り立つ。
 *   - area() は面積を返す
 *   - scaled(n) は各辺を n 倍した図形を返す。したがって面積は n^2 倍になる
 *
 * 「正方形は長方形の一種」というのは数学の話であって、
 * 「setWidth / setHeight を持つ可変な長方形」という型の話ではない。
 * 継承するかどうかは、名前や日常語の分類ではなく「振る舞いの契約を守れるか」で決める。
 */
public interface Shape {

    /** 面積。 */
    long area();

    /** 各辺を factor 倍した新しい図形を返す（自分自身は変更しない）。 */
    Shape scaled(int factor);
}
