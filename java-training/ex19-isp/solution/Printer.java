/**
 * 課題19 解答例: 印刷できる、という能力だけを表すインターフェース。
 *
 * インターフェース分離の原則（ISP）:
 *   「利用者は、自分が使わないメソッドへの依存を強制されるべきではない」
 *
 * 大きなインターフェースを1つ作ると
 *   - 実装側は使えない機能まで実装させられる（UnsupportedOperationException の温床）
 *   - 利用側は型からは何が呼べるか分からない（実行してみるまで壊れているか分からない）
 * 小さく分けておけば、必要な能力だけを引数の型で要求できる。
 */
public interface Printer {
    String print(String document);
}
